#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_openai_tool_roundtrip() {
        let openai_tool = serde_json::json!({
            "type": "function",
            "function": {
                "name": "get_weather",
                "description": "Get weather for a location",
                "strict": true,
                "parameters": {
                    "type": "object",
                    "properties": {
                        "location": {"type": "string"}
                    },
                    "required": ["location"],
                    "additionalProperties": false
                }
            }
        });

        let canonical = CanonicalTool::from_openai(&openai_tool).unwrap();
        assert_eq!(canonical.name, "get_weather");
        assert_eq!(canonical.strict, true);
        assert_eq!(canonical.execution, ToolExecution::ClientSide);

        let back = canonical.to_openai();
        assert_eq!(
            back["function"]["name"].as_str().unwrap(),
            "get_weather"
        );
        assert_eq!(back["function"]["strict"].as_bool().unwrap(), true);
    }

    #[test]
    fn test_anthropic_tool_roundtrip() {
        let anthropic_tool = serde_json::json!({
            "name": "get_weather",
            "description": "Get weather for a location",
            "input_schema": {
                "type": "object",
                "properties": {
                    "location": {"type": "string"}
                },
                "required": ["location"]
            },
            "cache_control": {"type": "ephemeral"}
        });

        let canonical = CanonicalTool::from_anthropic(&anthropic_tool).unwrap();
        assert_eq!(canonical.name, "get_weather");
        assert!(canonical.provider_hints.contains_key("cache_control"));

        let back = canonical.to_anthropic();
        assert_eq!(back["name"].as_str().unwrap(), "get_weather");
        assert!(back.get("cache_control").is_some());
    }

    #[test]
    fn test_openai_tool_call_roundtrip() {
        let openai_call = serde_json::json!({
            "id": "call_abc123",
            "type": "function",
            "function": {
                "name": "get_weather",
                "arguments": "{\"location\":\"Seattle\"}"
            }
        });

        let canonical = CanonicalToolCall::from_openai(&openai_call).unwrap();
        assert_eq!(canonical.id, "call_abc123");
        assert_eq!(canonical.name, "get_weather");
        assert_eq!(canonical.arguments["location"], "Seattle");

        let back = canonical.to_openai();
        assert_eq!(back["id"].as_str().unwrap(), "call_abc123");
    }

    #[test]
    fn test_anthropic_tool_call_roundtrip() {
        let anthropic_call = serde_json::json!({
            "type": "tool_use",
            "id": "toolu_01ABC",
            "name": "get_weather",
            "input": {"location": "Seattle"}
        });

        let canonical = CanonicalToolCall::from_anthropic(&anthropic_call).unwrap();
        assert_eq!(canonical.id, "toolu_01ABC");
        assert_eq!(canonical.name, "get_weather");

        let back = canonical.to_anthropic();
        assert_eq!(back["type"].as_str().unwrap(), "tool_use");
        assert_eq!(back["id"].as_str().unwrap(), "toolu_01ABC");
    }

    #[test]
    fn test_tool_result_to_openai() {
        let result = CanonicalToolResult {
            call_id: "call_abc123".into(),
            content: ToolResultContent::Text {
                text: "72°F, partly cloudy".into(),
            },
            is_error: false,
        };

        let msg = result.to_openai_message();
        assert_eq!(msg["role"].as_str().unwrap(), "tool");
        assert_eq!(msg["tool_call_id"].as_str().unwrap(), "call_abc123");
        assert_eq!(msg["content"].as_str().unwrap(), "72°F, partly cloudy");
    }

    #[test]
    fn test_tool_result_to_anthropic() {
        let result = CanonicalToolResult {
            call_id: "toolu_01ABC".into(),
            content: ToolResultContent::Text {
                text: "72°F, partly cloudy".into(),
            },
            is_error: true,
        };

        let block = result.to_anthropic_block();
        assert_eq!(block["type"].as_str().unwrap(), "tool_result");
        assert_eq!(block["tool_use_id"].as_str().unwrap(), "toolu_01ABC");
        assert_eq!(block["is_error"].as_bool().unwrap(), true);
    }

    #[test]
    fn test_tool_choice_conversions() {
        // OpenAI string forms
        assert_eq!(
            CanonicalToolChoice::from_openai(&serde_json::json!("auto")),
            CanonicalToolChoice::Auto
        );
        assert_eq!(
            CanonicalToolChoice::from_openai(&serde_json::json!("required")),
            CanonicalToolChoice::Required
        );

        // Anthropic object forms
        assert_eq!(
            CanonicalToolChoice::from_anthropic(&serde_json::json!({"type": "any"})),
            CanonicalToolChoice::Required
        );
        assert_eq!(
            CanonicalToolChoice::from_anthropic(&serde_json::json!({"type": "tool", "name": "get_weather"})),
            CanonicalToolChoice::Specific {
                name: "get_weather".into()
            }
        );

        // Round-trip
        let specific = CanonicalToolChoice::Specific {
            name: "search".into(),
        };
        let openai = specific.to_openai();
        assert_eq!(
            openai["function"]["name"].as_str().unwrap(),
            "search"
        );
        let anthropic = specific.to_anthropic();
        assert_eq!(anthropic["type"].as_str().unwrap(), "tool");
        assert_eq!(anthropic["name"].as_str().unwrap(), "search");
    }
}
